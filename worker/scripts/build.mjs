import { build } from "esbuild";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

// Compile trusted browser code first, then inline the exact outputs into an allowlisted module.
// No public filesystem binding or uploaded R2 object can become a catalog asset. Keeping modern
// ES2022 output also avoids Wrangler 3's old bundler breaking future PDF parser initialization.
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const bundle = async (path) => {
  const result = await build({
    absWorkingDir: root, entryPoints: [path], bundle: true, write: false,
    platform: "browser", format: "esm", target: "es2022", minify: false,
  });
  return result.outputFiles[0].text;
};
const [app, search, styles, shell] = await Promise.all([
  bundle("src/ui/app.ts"), bundle("src/ui/search-worker.ts"), bundle("src/ui/styles.css"),
  readFile(resolve(root, "src/ui/index.html"), "utf8"),
]);
const assets = {
  "/all-docs": { type: "text/html; charset=utf-8", body: shell },
  "/all-docs/assets/app.js": { type: "text/javascript; charset=utf-8", body: app },
  "/all-docs/assets/search-worker.js": { type: "text/javascript; charset=utf-8", body: search },
  "/all-docs/assets/styles.css": { type: "text/css; charset=utf-8", body: styles },
};
await mkdir(resolve(root, ".wrangler/generated"), { recursive: true });
await writeFile(resolve(root, ".wrangler/generated/catalog-assets.ts"),
  `// Generated by scripts/build.mjs; edit src/ui instead.\nexport const assets: Record<string, {type: string; body: string}> = ${JSON.stringify(assets)};\n`);
await build({
  absWorkingDir: root, entryPoints: ["src/index.ts"], outfile: ".wrangler/build/index.js",
  bundle: true, format: "esm", platform: "browser", target: "es2022",
});
